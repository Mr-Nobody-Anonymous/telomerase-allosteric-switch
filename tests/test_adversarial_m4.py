class TestBiologicalFidelityAndBenchmarkParity:
    """Stress tests verifying biological fidelity and numeric consistency with literature."""

    def test_catalytic_core_rigidity_across_7trd_and_7trf(self, raw_dir: Path):
        """
        Catalytic core (326-1132, 770 C-alpha) must act as a rigid monolith
        with identical RMSD (0.3377 A) between 7TRE vs 7TRD and 7TRE vs 7TRF.
        """
        df = compute_cross_state_rmsd(raw_dir=raw_dir)

        core_td = df[
            (df["target_structure"] == "7TRE")
            & (df["reference_structure"] == "7TRD")
            & (df["alignment_selection"] == "Catalytic Core")
        ].iloc[0]

        core_tf = df[
            (df["target_structure"] == "7TRE")
            & (df["reference_structure"] == "7TRF")
            & (df["alignment_selection"] == "Catalytic Core")
        ].iloc[0]

        assert int(core_td["num_aligned_ca_atoms"]) == 770
        assert int(core_tf["num_aligned_ca_atoms"]) == 770
        assert abs(float(core_td["rmsd_angstrom"]) - 0.338) < 0.01
        assert abs(float(core_tf["rmsd_angstrom"]) - 0.338) < 0.01
        assert abs(float(core_td["rmsd_angstrom"]) - float(core_tf["rmsd_angstrom"])) < 1e-4

    def test_ten_domain_hinge_excursion_exceeds_catalytic_core(self, raw_dir: Path):
        """
        TEN domain displacement on catalytic core fit (~0.434 A) must strictly exceed
        its independent RMSD (~0.411 A), demonstrating rigid-body hinge motion.
        """
        df = compute_domain_rmsds(raw_dir=raw_dir)

        ten_row = df[
            (df["target_structure"] == "7TRE")
            & (df["reference_structure"] == "7TRD")
            & (df["domain_name"] == "TEN")
        ].iloc[0]

        indep = float(ten_row["independent_rmsd_angstrom"])
        core_fit = float(ten_row["core_fit_displacement_angstrom"])

        assert indep < core_fit, (
            f"Core-fit displacement ({core_fit} A) must exceed independent RMSD ({indep} A)"
        )
        assert abs(indep - 0.4112) < 0.01
        assert abs(core_fit - 0.4341) < 0.01

    def test_tpp1_tel_patch_plasticity_contrast(self, raw_dir: Path):
        """
        TEL-patch conformational contrast:
        - Leu183 is a rigid hydrophobic anchor (disp = 0.512 A, 'Rigid Anchor').
        - Glu169, Lys170, Glu171 undergo plastic remodeling (> 3.0 A, 'Extensive Remodeling').
        - Lys170 exhibits peak loop displacement (4.293 A).
        """
        df = compute_tpp1_conformational_shifts(raw_dir=raw_dir)

        leu183 = df[df["auth_seq_id"] == 183].iloc[0]
        assert leu183["resname"] == "LEU"
        assert leu183["conformational_shift_flag"] == "Rigid Anchor"
        assert abs(float(leu183["ca_distance_7tre_vs_2i46_angstrom"]) - 0.512) < 0.02

        lys170 = df[df["auth_seq_id"] == 170].iloc[0]
        assert lys170["resname"] == "LYS"
        assert lys170["conformational_shift_flag"] == "Extensive Remodeling"
        assert abs(float(lys170["ca_distance_7tre_vs_2i46_angstrom"]) - 4.293) < 0.02

        glu169 = df[df["auth_seq_id"] == 169].iloc[0]
        assert glu169["conformational_shift_flag"] == "Extensive Remodeling"
        assert float(glu169["ca_distance_7tre_vs_2i46_angstrom"]) > 3.5

        glu171 = df[df["auth_seq_id"] == 171].iloc[0]
        assert glu171["conformational_shift_flag"] == "Extensive Remodeling"
        assert float(glu171["ca_distance_7tre_vs_2i46_angstrom"]) > 3.0

    def test_per_residue_displacement_profile_completeness(self, raw_dir: Path):
        """
        Per-residue C-alpha displacement table must contain exactly 934 residues
        with zero NaNs and core mean displacement < TEN mean displacement.
        """
        df = compute_per_residue_displacement(raw_dir=raw_dir)
        assert len(df) == 934
        assert not df.isna().any().any(), "Displacement table must contain zero NaNs"

        core_mask = df["domain"].isin(["TRBD", "RT", "IFD_TRAP", "CTE"])
        ten_mask = df["domain"] == "TEN"

        disp_core = df.loc[core_mask, "disp_7tre_vs_7trd_core_fit_angstrom"]
        disp_ten = df.loc[ten_mask, "disp_7tre_vs_7trd_core_fit_angstrom"]

        assert float(disp_core.mean()) < 0.31
        assert float(disp_ten.mean()) > 0.38
        assert float(disp_ten.mean()) > float(disp_core.mean())
