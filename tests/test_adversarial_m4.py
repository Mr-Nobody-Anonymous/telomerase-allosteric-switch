class TestKabschChiralityAndReflectionGuards:
    """Stress tests verifying strict prevention of improper reflections (chirality flipping)."""

    def test_chiral_asymmetric_tetrahedron_reflection_rejected(self):
        """
        Adversarial reflection attack on chiral tetrahedron:
        Kabsch must enforce det(R) == +1.0 and RMSD > 0, NEVER allowing det(R) == -1.0.
        """
        # Define chiral tetrahedron with non-zero signed volume
        tet = np.array([
            [0.0, 0.0, 0.0],
            [2.0, 0.0, 0.0],
            [0.0, 3.0, 0.0],
            [0.0, 0.0, 4.0],
        ], dtype=float)

        signed_vol = float(np.linalg.det(tet[1:] - tet[0]))
        assert abs(signed_vol) > 1.0, "Tetrahedron must be non-degenerate"

        # Reflections along X, Y, Z axes
        for axis_idx in (0, 1, 2):
            refl = tet.copy()
            refl[:, axis_idx] = -refl[:, axis_idx]

            res = svd_kabsch_align(coords_target=tet, coords_mobile=refl)
            det = float(np.linalg.det(res.rotation))

            assert abs(det - 1.0) < 1e-8, f"det(R) must be +1.0, got {det}"
            assert res.rmsd > 0.1, (
                f"Chiral enantiomer reflection must NOT superimpose with 0 RMSD, got {res.rmsd}"
            )

    def test_arbitrary_hyperplane_reflection_monte_carlo(self):
        """Monte Carlo reflection across 50 arbitrary plane normals."""
        rng = np.random.default_rng(888)

        for _ in range(50):
            pts = rng.uniform(-10, 10, size=(6, 3))
            vol = np.linalg.det(pts[1:4] - pts[0])
            if abs(vol) < 0.5:
                continue

            normal = rng.normal(size=3)
            normal /= np.linalg.norm(normal)
            # Householder reflection matrix H = I - 2 * n * n^T (det == -1)
            h_mat = np.eye(3) - 2.0 * np.outer(normal, normal)
            assert abs(np.linalg.det(h_mat) - (-1.0)) < 1e-10

            pts_reflected = pts @ h_mat.T

            res = svd_kabsch_align(coords_target=pts, coords_mobile=pts_reflected)
            det = float(np.linalg.det(res.rotation))

            assert abs(det - 1.0) < 1e-8, f"Kabsch permitted improper reflection: det={det}"
            assert res.rmsd > 0.05, f"Expected non-zero RMSD on reflected object, got {res.rmsd}"

    def test_full_inversion_through_origin_rejected(self):
        """Inversion through origin (x, y, z) -> (-x, -y, -z) has det == -1 and must be rejected."""
        pts = np.array([
            [1.0, 2.0, 3.0],
            [4.0, 1.0, 2.0],
            [2.0, 5.0, 1.0],
            [3.0, 4.0, 5.0],
        ], dtype=float)
        inverted = -pts.copy()

        res = svd_kabsch_align(coords_target=pts, coords_mobile=inverted)
        det = float(np.linalg.det(res.rotation))
        assert abs(det - 1.0) < 1e-8
        assert res.rmsd > 1.0

    def test_real_protein_chiral_reflection_attack(self, cif_7tre: Path):
        """
        Adversarial mirror reflection applied to genuine 7TRE TERT (934 C-alpha atoms).
        Verifies that Kabsch refuses to invert chirality, yielding det(R) == +1.0 and RMSD > 30 A.
        """
        ca_dict = extract_ca_coordinates(cif_7tre, "A", use_auth=True)
        coords = np.array([ca_dict[r][1] for r in sorted(ca_dict.keys())])

        refl_coords = coords.copy()
        refl_coords[:, 2] = -refl_coords[:, 2]  # Z mirror reflection

        res = svd_kabsch_align(coords_target=coords, coords_mobile=refl_coords)
        det = float(np.linalg.det(res.rotation))

        assert abs(det - 1.0) < 1e-8, f"det(R) {det} violated SO(3)"
        assert res.rmsd > 30.0, f"Expected RMSD > 30 A on reflected protein, got {res.rmsd}"

    def test_coplanar_in_plane_reflection_achieved_via_proper_rotation(self):
        """
        For coplanar points in z=0, reflection across an axis in the plane CAN be
        achieved in SO(3) by a 180-degree out-of-plane rotation (det == +1).
        Kabsch must correctly identify this proper rotation and achieve RMSD < 1e-12.
        """
        # Coplanar points in z=0
        coplanar = np.array([
            [1.0, 2.0, 0.0],
            [3.0, 1.0, 0.0],
            [2.0, 4.0, 0.0],
            [5.0, 3.0, 0.0],
        ], dtype=float)

        # In-plane reflection: x -> -x
        refl = coplanar.copy()
        refl[:, 0] = -refl[:, 0]

        res = svd_kabsch_align(coords_target=coplanar, coords_mobile=refl)
        det = float(np.linalg.det(res.rotation))

        assert abs(det - 1.0) < 1e-8, f"Rotation matrix must be in SO(3), got det={det}"
        assert res.rmsd < 1e-12, (
            f"Coplanar in-plane reflection should be resolved by 180-deg flip with RMSD ~0, got {res.rmsd}"
        )


