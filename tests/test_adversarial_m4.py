    def test_2i46_chain_b_disorder_and_redirection_guardrail(self, cif_2i46: Path):
        """
        Verify that 2I46 Chain B genuinely lacks TEL-patch DE-loop residues 168-171,
        and select_valid_tpp1_chain enforces Chain A redirection.
        """
        # Inspect raw coordinates of Chain B
        ca_b = extract_ca_coordinates(cif_2i46, "B", use_auth=True)
        de_loop_residues = [168, 169, 170, 171]
        for r in de_loop_residues:
            assert r not in ca_b, f"Residue {r} should be disordered in 2I46 Chain B"

        # select_valid_tpp1_chain with require_tel_patch=True redirects to Chain A
        ch = select_valid_tpp1_chain(cif_2i46, preferred_chain="B", require_tel_patch=True)
        assert ch == "A", f"Expected redirection to Chain A, got {ch}"

        # Chain A contains all DE-loop residues
        ca_a = extract_ca_coordinates(cif_2i46, "A", use_auth=True)
        for r in de_loop_residues:
            assert r in ca_a, f"Residue {r} must be resolved in 2I46 Chain A"


