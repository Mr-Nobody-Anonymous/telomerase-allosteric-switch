"""
WP36 - The circular-inference audit.

WHY THIS EXISTS
---------------
Four separate failures in this programme were the same mistake, so fixing the
numbers one at a time was never going to stop the next one.  The class is
CIRCULAR INFERENCE: a quantity is computed from a construction that already
contains the conclusion, then reported as evidence for the conclusion.

Every instance passes every arithmetic check, because the arithmetic is right.
What is wrong is the claim attached to it.  That is why it survived review.

This module makes the class testable.  For each instance there is a PREDICATE
that is true of the circular construction and false of a genuine one.

THE FIVE INSTANCES
------------------
C1  "M5 independently reproduces the 48 nt L&C observed."
    delta* = 1/log2(1+a) with a = s^(-1/n)-1 and s = 2^(-1/R) is
    IDENTICALLY n*R.  So 47.98 bp IS 6 x 8 nt: the claim compares 6x8 with 8x6.
    PREDICATE: the "agreement" holds for every exponent n.  Swept n = 1..24,
    delta* tracks n while the fold kappa moves 7.5% - so delta* carries no
    information and kappa is the only informative statistic.

C2  "The stalled fraction explains 88% of the gap."
    (s0-phi0)/s0 is a function of the two quantities whose mismatch IS the
    anomaly, so it cannot explain it.
    PREDICATE: negative where phi -> 1 (-0.0796 in the +PT arm).  A fraction of
    a population cannot be negative.

C3  "Synchronised confirmation versus chance."
    The expected value was drawn from the null being tested.
    PREDICATE: the "expected" value equals the null exactly.

C4  "Removing all 12 loops changes the output by 4.4%."
    The loop detector and the loop remover share a definition.
    PREDICATE: the invariance holds for ANY input, including random ones.

C5  "The physical SPR / RAP benchmark datasets."
    data/benchmarks/*.csv is generated by np.random.seed(42) from chosen
    k_on / k_off / R_max.
    PREDICATE: refitting recovers the generating parameters essentially exactly.

C6  "M5 passes an out-of-sample test on Wang 2007, a second enzyme."
    It does not. There is NO measured off-rate for Wang - WP22's own table says
    "measured: not measured". The 4.48x is a0/a1 computed from Wang's two
    R1/2 values, so feeding it back returns Wang's input exactly (2e-15).
    The only measured fold anywhere is L&C's >=4x, and that is the datum M5 was
    built on.
    PREDICATE: the "prediction" recovers its own input to machine precision.

C7  "delta* decides the maintenance gate."
    With the fold held FIXED at 3.267, delta* still runs 8 -> 231 bp/PD as the
    assumed exponent n goes 1 -> 24, because delta* = n * R_eff. Nothing in the
    repository measures n, and n and tau are CONFOUNDED: several (n, tau) pairs
    give the same fold.
    PREDICATE: delta* at a fixed fold depends on n alone.

    python scripts/solve/wp36_circularity.py
    -> results/solve/wp36_circularity.csv
    -> results/solve/wp36_circularity.json

    python scripts/solve/wp36_circularity.py --self-test
"""

