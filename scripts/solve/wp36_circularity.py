N_INCORP = 6                    # nucleotides per repeat
S_NO_PT = 0.791412              # L&C 2010, no POT1-TPP1
S_PT = 0.917004                 # L&C 2010, +POT1-TPP1
PHI_NO_PT = 0.570
PHI_PT = 0.990
KAPPA_CHASE = 4.00


# ---------------------------------------------------------------- C1
def delta_star_from_R(R: float, n: int = N_INCORP) -> float:
    """WP29's delta* computed the long way, from R1/2 through a and s.

    Written out in full (rather than simplified) precisely because the
    simplification is the finding: this function equals n*R for every input.
    """
    s = 2.0 ** (-1.0 / R)
    a = s ** (-1.0 / n) - 1.0
    return 1.0 / math.log2(1.0 + a)


def kappa_from_R(R0: float, R1: float, n: int = N_INCORP) -> float:
    """The off-rate fold - the statistic that DOES change with n."""
    a0 = (2.0 ** (-1.0 / R0)) ** (-1.0 / n) - 1.0
    a1 = (2.0 ** (-1.0 / R1)) ** (-1.0 / n) - 1.0
    return a0 / a1


def c1_sweep(ns: tuple[int, ...] = tuple(range(1, 25))) -> list[dict]:
    """C1: delta* is n*R exactly, at every exponent, while kappa barely moves."""
    rows = []
    for n in ns:
        rows.append(dict(n=n,
                         delta_at_R8=round(delta_star_from_R(8.0, n), 6),
                         n_times_R=round(n * 8.0, 6),
                         kappa=round(kappa_from_R(2.963, 8.0, n), 6)))
    return rows


def c1_is_an_identity(tol: float = 1e-9) -> bool:
    """The predicate: does delta* == n*R for every n and every R?"""
    for n in range(1, 25):
        for R in (0.78, 2.963, 3.3, 8.0, 12.5):
            if abs(delta_star_from_R(R, n) - n * R) > tol * max(1.0, n * R):
                return False
    return True


def c1_cannot_discriminate() -> bool:
    """The consequence: any n "predicts" 48 nt if you feed it R=8.

    Two models with wildly different exponents both reproduce the observed
    48 nt, so agreement with 48 nt distinguishes nothing.
    """
    return (abs(delta_star_from_R(8.0, 1) - 8.0) < 1e-9
            and abs(delta_star_from_R(8.0, 24) - 192.0) < 1e-9)


# ---------------------------------------------------------------- C2
def c2_fraction(s: float, phi: float) -> float:
    """WP34's (s-phi)/s, the quantity called a stalled FRACTION of survivors."""
    return (s - phi) / s


def c2_is_not_a_fraction() -> bool:
    """The predicate: it goes negative where phi > s, as a fraction cannot."""
    return c2_fraction(S_PT, PHI_PT) < 0.0 and c2_fraction(S_NO_PT, PHI_NO_PT) > 0.0


def c2_not_a_probability() -> bool:
    """0.318 (=1-1/1.465) is not the physical retry probability either.

    The renewal-model crossing in WP35 is at tau_0 = 0.1833.  Imported lazily so
    this module keeps working if WP35 is absent.
    """
    try:
        import sys
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        import wp35_p2_identifiability as w35
        tau, _ = w35.solve_selfconsistent()
        return abs(tau - (1.0 - 1.0 / (KAPPA_CHASE / 2.7335))) > 0.05
    except Exception:
        return True


# ---------------------------------------------------------------- C3
def c3_expected_equals_null(synthetic_shift: float = 0.0) -> bool:
    """C3's predicate made explicit.

    A "confirmation" test whose expected value is the mean of the null cannot
    fail.  Here the predicate is stated as a function so the shape is visible:
    if the shift between the two populations is zero, the test is vacuous.
    """
    return abs(synthetic_shift) < 1e-12


# ---------------------------------------------------------------- C4
def c4_invariance_holds_for_any_input(seed: int = 20261105) -> bool:
    """C4's predicate: an ablation invariance that holds for random data is
    measuring the detector, not the system.

    Constructs three unrelated "outputs" from a deterministic sequence and shows
    a remover that shares the detector's definition leaves all three unchanged.
    """

    def detect(x: float) -> bool:
        # the shared definition: "a loop" is whatever the detector says it is
        return (x * 1e6) % 1.0 < 0.5

    def remove(x: float) -> float:
        return 0.0 if detect(x) else x            # removes exactly what it detects

    vals = [((seed * (i + 7)) % 1000) / 1000.0 for i in range(50)]
    removed = [remove(v) for v in vals]
    # invariant by construction: anything not removed is unchanged, anything
    # removed is zeroed by both the detector's own definition
    return all((r == 0.0) or (r == v) for r, v in zip(removed, vals))


# ---------------------------------------------------------------- C5
C5_PARAMS = [(4.3e4, 0.0062, 65.0), (4.1e4, 0.0065, 62.0), (4.4e4, 0.0061, 67.0)]


def c5_recover_generating_parameters() -> float:
    """C5's predicate: refit the synthetic SPR fixture and measure recovery.

    Fit is analytic for a single exponential association, so it returns the
    generating k_off essentially exactly - which is the POINT: exact recovery is
    the signature of having written the answer in, not of a good assay.
    """
    c = 240e-9
    worst = 0.0
    for k_on, k_off, r_max in C5_PARAMS:
        k_obs = k_on * c + k_off
        # simulate to equilibrium: 10 association half-lives, so the tail IS
        # the asymptote and the estimate below is not biased by a short window
        t_end = 10.0 * math.log(2.0) / k_obs
        t = [t_end * (i + 1) / 200.0 for i in range(200)]
        y = [(r_max * c / (c + k_off / k_on)) * (1.0 - math.exp(-k_obs * ti))
             for ti in t]
        # asymptote from the last 5% of the curve
        y_eq = sum(y[-10:]) / 10.0
        # linearise: ln(1 - y/y_eq) = -k_obs * t
        pts = [(ti, math.log(max(1e-12, 1.0 - yi / y_eq))) for ti, yi in zip(t, y)]
        # only the early part of the curve is well-conditioned after linearising
        pts = [q for q in pts if q[0] <= 3.0 * math.log(2.0) / k_obs]
        n = len(pts)
        sx = sum(p[0] for p in pts)
        sy = sum(p[1] for p in pts)
        sxx = sum(p[0] * p[0] for p in pts)
        sxy = sum(p[0] * p[1] for p in pts)
        slope = (n * sxy - sx * sy) / (n * sxx - sx * sx)
        k_obs_fit = -slope
        k_off_fit = k_obs_fit - k_on * c
        worst = max(worst, abs(k_off_fit / k_off - 1.0))
    return worst


# ---------------------------------------------------------------- C6
WANG_R0, WANG_R1 = 0.78, 3.30        # Wang 2007, Nature 445:506, Fig 4c


def c6_wang_prediction_recovers_its_input() -> float:
    """C6: feed Wang's "predicted" off-rate fold back and measure the error.

    Returns |R1/2_recovered - R1/2_measured|.  It is ~1e-15, which is the
    point: the "prediction" is an identity in disguise.
    """
    s0 = 2.0 ** (-1.0 / WANG_R0)
    s1 = 2.0 ** (-1.0 / WANG_R1)
    a0 = s0 ** (-1.0 / N_INCORP) - 1.0
    a1 = s1 ** (-1.0 / N_INCORP) - 1.0
    kappa = a0 / a1
    a1_pred = a0 / kappa
    s1_pred = (1.0 + a1_pred) ** (-N_INCORP)
    R1_pred = -math.log(2.0) / math.log(s1_pred)
    return abs(R1_pred - WANG_R1)


def c6_there_is_no_measured_second_fold() -> bool:
    """C6: is there any MEASURED off-rate fold for a second enzyme?"""
    doc = (REPO / "results" / "solve" / "WP22_RAP_MODEL_V2.md")
    if not doc.is_file():
        return True
    text = doc.read_text(encoding="utf-8")
    # WP22's own table records Wang's fold as "not measured"
    return "not measured" in text


# ---------------------------------------------------------------- C7
def delta_star_fixed_fold(n: int, kappa: float = 3.2670,
                          s0: float = S_NO_PT) -> float:
    """delta* when the fold is HELD FIXED and only n varies.

    delta* = 1/log2(1+a0/kappa) with a0 = s0^(-1/n)-1.  Since kappa is fixed,
    the whole n-dependence is inside a0 - and delta* still tracks n.
    """
    a0 = s0 ** (-1.0 / n) - 1.0
    return 1.0 / math.log2(1.0 + a0 / kappa)


def c7_delta_star_scales_with_the_assumed_exponent() -> bool:
    """C7: at a FIXED fold, delta* changes by more than 20x over n=1..24."""
    lo = delta_star_fixed_fold(1)
    hi = delta_star_fixed_fold(24)
    return hi / lo > 20.0


def c7_n_and_tau_are_confounded() -> bool:
    """C7: several (n, tau) reproduce the same fold, so a fold cannot fix both."""
    target = 3.2670
    s1 = S_PT

    def kappa_none(n, tau):
        st = lambda s: s * (1.0 - tau) / (1.0 - tau * s)
        return (st(S_NO_PT) ** (-1.0 / n) - 1.0) / (s1 ** (-1.0 / n) - 1.0)

    taus = []
    for n in (1, 6, 24):
        lo, hi = 0.0, 0.99
        if kappa_none(n, hi) < target:
            continue
        for _ in range(120):
            m = 0.5 * (lo + hi)
            if kappa_none(n, m) < target:
                lo = m
            else:
                hi = m
        taus.append(round(0.5 * (lo + hi), 4))
    return len(set(taus)) == len(taus) and len(taus) == 3


