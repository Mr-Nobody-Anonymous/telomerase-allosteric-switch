def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        while chunk := fh.read(65536):
            h.update(chunk)
    return h.hexdigest()


def marker_counts() -> dict[str, dict[str, int]]:
    """Every marker occurrence in results/solve, per file and per state."""
    out = {}
    for f in sorted(SOLVE.glob("*.md")):
        text = f.read_text(encoding="utf-8")
        counts = {s: len(re.findall(rf"\b{s}\b", text)) for s in STATES}
        if any(counts.values()):
            out[str(f.relative_to(REPO))] = counts
    return out


def check_register() -> list[str]:
    """Problems with the register itself, checked against the tree."""
    problems = []
    seen = set()
    for r in REGISTER:
        if r["id"] in seen:
            problems.append(f"duplicate id {r['id']}")
        seen.add(r["id"])
        if r["state"] not in STATES:
            problems.append(f"{r['id']}: state {r['state']!r} not in {STATES}")
        path = REPO / r["file"]
        if not path.is_file():
            problems.append(f"{r['id']}: missing file {r['file']}")
            continue
        text = " ".join(path.read_text(encoding="utf-8").split())
        if r["must_contain"] not in text:
            problems.append(
                f"{r['id']}: {r['file']} no longer contains {r['must_contain']!r}")
    return problems


def unregistered_markers() -> list[str]:
    """Documents that carry a marker but appear nowhere in the register."""
    registered = {r["file"] for r in REGISTER}
    generated = {"results/solve/RETRACTIONS.md"}   # the register quotes itself
    out = []
    for f, counts in marker_counts().items():
        if f in registered or f in generated:
            continue
        # WP36's own tables and OPEN_GAPS list instances without carrying them
        out.append(f"{f} ({ ', '.join(f'{s}x{n}' for s, n in counts.items() if n) })")
    return out


def render_markdown() -> str:
    rows = "\n".join(
        f"| **{r['id']}** | {r['state']} | {r['claim']} | {r['actual']} | "
        f"{r['predicate']} | {r['replaced_by']} | `{r['file']}` |"
        for r in REGISTER
    )
    counts = {s: sum(1 for r in REGISTER if r["state"] == s) for s in STATES}
    tally = ", ".join(f"{n} {s.lower()}" for s, n in counts.items() if n)
    by_wp: dict[str, int] = {}
    for r in REGISTER:
        by_wp[r["wp"]] = by_wp.get(r["wp"], 0) + 1
    def _key(kv):
        k = kv[0]
        return (0, int(k)) if k.isdigit() else (1, 0)
    wp_line = ", ".join(f"WP{k} ×{v}" if k.isdigit() else f"pre-WP22 ×{v}"
                        for k, v in sorted(by_wp.items(), key=_key))
    return f"""# Retraction register — generated, do not edit by hand

    python scripts/solve/wp38_archive.py
    python scripts/solve/wp38_archive.py --self-test

**{len(REGISTER)} registered retractions: {tally}.**
Raised by: {wp_line}.

This file is **generated** from `scripts/solve/wp38_archive.py`. `--self-test`
re-derives it and compares; if a marker is deleted from a source document, or a
refuted claim is added without registering it, the suite fails. That is the
difference between an archive and a filing cabinet.

Four vocabularies had grown up in the tree (`RETRACTED`, `WITHDRAWN`,
`SUPERSEDED`, `CORRECTED`). They are kept, because each means something slightly
different, but they are now **fixed** and all four are enumerated:

| state | means |
|---|---|
| **RETRACTED** | the claim was wrong and nothing replaces it in the same form |
| **WITHDRAWN** | the claim was not demonstrated at all |
| **SUPERSEDED** | the claim was true as far as it went, and is now replaced |
| **CORRECTED** | the claim stands but was mislabelled |

---

## Register

| id | state | claimed | actually was | predicate that exposed it | replaced by | document |
|---|---|---|---|---|---|---|
{rows}

---

## What the register makes checkable

Every entry carries a **predicate** — a statement true of the defective
construction and false of a genuine one. That is what stopped this class of error
from being a matter of opinion:

- C1 — the "agreement" holds for *every* exponent, so it distinguishes nothing;
- C2 — the quantity is *negative* in the +PT arm, so it is not a fraction;
- C5 — refitting recovers the generating parameters, i.e. the answer was written in;
- C6 — the "prediction" recovers its own input to `2e-15`;
- C7 — at a **fixed** fold, `δ*` moves 26× with an unmeasured exponent.

## What is deliberately *not* in the register

Not everything superseded is a retraction. The following are **current** and
carry no marker:

- `WP36_CIRCULARITY.md` itself (it is the audit, not a retracted claim);
- `WP37_MISSING.md` (it closes four gaps);
- the candidate ranking and the pipeline arithmetic in `WP34_STATUS.md`, which
  survive the retraction of its 88 % figure;
- **`CLM-023` / `PA-019` (TELIN-1)** — quarantined, `untested` / `Unvalidated
  Proposal`. Quarantine is not a retraction and this register does not lift it.

**No therapeutic claim is made or supported anywhere in this repository.**
"""


