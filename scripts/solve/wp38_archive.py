#!/usr/bin/env python3
"""
WP38 - Archive the programme: one mechanical retraction register, and a freeze.

WHY THIS EXISTS
---------------
Asked "did you archive it", the honest answer was no.  Everything was committed
and pushed, but:

  * there was **no tag and no release**, so there is no immutable snapshot;
  * retractions were recorded *only* as markers scattered across 10 documents in
    FOUR different vocabularies (RETRACTED / WITHDRAWN / SUPERSEDED / CORRECTED);
  * nothing checked that the set was complete, so a refuted claim could survive
    in a document nobody re-read.

That last point is the important one.  A retraction that exists only in the head
of whoever wrote the post-mortem is not a retraction.  So this script does not
write the register by hand - it **derives** it from the tree, and fails if the
tree and the register disagree.

WHAT IT PRODUCES
----------------
  results/solve/RETRACTIONS.md      the register, generated, never hand-edited
  results/solve/retractions.csv     the same, flat
  results/solve/retractions.json    the same, with file SHA-256s

It also runs two NEGATIVE CONTROLS on every build: every document that carries a
marker must be in the register, and no marker vocabulary outside the four fixed
states may exist.  Both are printed on every run, not only in the test, because
the failure mode here is silence.

Each row records: the id, what was claimed, what it actually was, the predicate
that exposes it, what replaced it, and the exact fingerprint of the marker text
in the document that carries it.

THE TEST
--------
`--self-test` re-derives the register and compares it to the committed file.  If
someone deletes a marker, or adds a retracted claim without registering it, the
suite fails.  That is the difference between an archive and a filing cabinet.

    python scripts/solve/wp38_archive.py
    python scripts/solve/wp38_archive.py --self-test
"""

